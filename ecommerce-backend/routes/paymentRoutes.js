const express = require("express");

const {
  createRazorpayOrder,
  verifyRazorpayPayment,
} = require("../controllers/paymentController");

const { protect } = require("../middlewares/authMiddleware");

const idempotencyMiddleware = require("../middlewares/idempotencyMiddleware");

const router = express.Router();

/**
 * @swagger
 * /api/payments/razorpay/create:
 *   post:
 *     summary: Create a Razorpay payment order
 *     description: Creates a Razorpay order for an existing unpaid order. The authenticated user must own the order.
 *     tags:
 *       - Payments
 *     security:
 *       - cookieAuth: []
 *     parameters:
 *       - in: header
 *         name: Idempotency-Key
 *         required: true
 *         schema:
 *           type: string
 *         description: Unique key used to safely retry the payment-order creation request.
 *         example: payment-order-12345
 *     requestBody:
 *       required: true
 *       content:
 *         application/json:
 *           schema:
 *             type: object
 *             required:
 *               - orderId
 *             properties:
 *               orderId:
 *                 type: string
 *                 description: ID of the existing order to be paid.
 *                 example: 65a123456789abcdef123456
 *     responses:
 *       201:
 *         description: Razorpay order created successfully
 *         content:
 *           application/json:
 *             schema:
 *               type: object
 *               properties:
 *                 success:
 *                   type: boolean
 *                   example: true
 *                 message:
 *                   type: string
 *                   example: Razorpay order created successfully
 *                 data:
 *                   type: object
 *                   properties:
 *                     razorpayOrderId:
 *                       type: string
 *                       example: order_Nx123456789
 *                     amount:
 *                       type: integer
 *                       description: Amount in paise.
 *                       example: 199900
 *                     currency:
 *                       type: string
 *                       example: INR
 *                     key:
 *                       type: string
 *                       example: rzp_test_123456789
 *                     orderId:
 *                       type: string
 *                       example: 65a123456789abcdef123456
 *       400:
 *         description: Order ID missing or order is already paid
 *       401:
 *         description: Authentication required
 *       403:
 *         description: User is not allowed to pay for this order
 *       404:
 *         description: Order not found
 */
router.post(
  "/razorpay/create",
  protect,
  idempotencyMiddleware,
  createRazorpayOrder,
);

/**
 * @swagger
 * /api/payments/razorpay/verify:
 *   post:
 *     summary: Verify a Razorpay payment
 *     description: Verifies the Razorpay payment signature and marks the associated order as paid.
 *     tags:
 *       - Payments
 *     security:
 *       - cookieAuth: []
 *     requestBody:
 *       required: true
 *       content:
 *         application/json:
 *           schema:
 *             type: object
 *             required:
 *               - razorpay_payment_id
 *               - razorpay_order_id
 *               - razorpay_signature
 *             properties:
 *               razorpay_payment_id:
 *                 type: string
 *                 description: Razorpay payment ID returned after successful payment.
 *                 example: pay_Nx987654321
 *               razorpay_order_id:
 *                 type: string
 *                 description: Razorpay order ID associated with the payment.
 *                 example: order_Nx123456789
 *               razorpay_signature:
 *                 type: string
 *                 description: Signature generated by Razorpay for payment verification.
 *                 example: 9f4e8b7c6d5a4e3f2b1a
 *     responses:
 *       200:
 *         description: Payment verified successfully
 *         content:
 *           application/json:
 *             schema:
 *               type: object
 *               properties:
 *                 success:
 *                   type: boolean
 *                   example: true
 *                 message:
 *                   type: string
 *                   example: Payment verified successfully.
 *                 data:
 *                   type: object
 *                   description: Updated order object.
 *       400:
 *         description: Payment verification data is incomplete or signature is invalid
 *       401:
 *         description: Authentication required
 *       403:
 *         description: User is not allowed to verify this payment
 *       404:
 *         description: Order not found
 */
router.post(
    "/razorpay/verify", 
    protect, 
    verifyRazorpayPayment
);

module.exports = router;
